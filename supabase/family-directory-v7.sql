-- Kantha Pranth V7: richer Family Directory
-- Run once in Supabase SQL Editor.

ALTER TABLE public.families
  ALTER COLUMN family_name DROP NOT NULL;

ALTER TABLE public.families
  ADD COLUMN IF NOT EXISTS phone text,
  ADD COLUMN IF NOT EXISTS email text,
  ADD COLUMN IF NOT EXISTS address text,
  ADD COLUMN IF NOT EXISTS show_contact boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS photo_path text;

-- Private family-photo storage. Photos are not publicly indexed.
INSERT INTO storage.buckets (id, name, public)
VALUES ('family-photos', 'family-photos', false)
ON CONFLICT (id) DO NOTHING;

-- Owners can upload/update photos under their own user-id folder.
DROP POLICY IF EXISTS "family photo owner upload" ON storage.objects;
CREATE POLICY "family photo owner upload"
ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'family-photos'
  AND (storage.foldername(name))[1] = (SELECT auth.uid()::text)
);

DROP POLICY IF EXISTS "family photo owner update" ON storage.objects;
CREATE POLICY "family photo owner update"
ON storage.objects
FOR UPDATE TO authenticated
USING (
  bucket_id = 'family-photos'
  AND (storage.foldername(name))[1] = (SELECT auth.uid()::text)
)
WITH CHECK (
  bucket_id = 'family-photos'
  AND (storage.foldername(name))[1] = (SELECT auth.uid()::text)
);

DROP POLICY IF EXISTS "family photo owner delete" ON storage.objects;
CREATE POLICY "family photo owner delete"
ON storage.objects
FOR DELETE TO authenticated
USING (
  bucket_id = 'family-photos'
  AND (storage.foldername(name))[1] = (SELECT auth.uid()::text)
);

-- Signed URLs are generated by authenticated users. The object path contains
-- the owner's user id and the family UUID, so it is not exposed as a public URL.
DROP POLICY IF EXISTS "authenticated users can view family photos" ON storage.objects;
CREATE POLICY "authenticated users can view family photos"
ON storage.objects
FOR SELECT TO authenticated
USING (bucket_id = 'family-photos');

NOTIFY pgrst, 'reload schema';
